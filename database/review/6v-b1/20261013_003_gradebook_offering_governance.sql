CREATE TABLE gradebook_offering_governance (
    subject_offering_id BIGINT UNSIGNED NOT NULL,
    school_id BIGINT UNSIGNED NOT NULL,
    academic_year_id BIGINT UNSIGNED NOT NULL,
    cutover_epoch_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    origin VARCHAR(20) NOT NULL,
    state VARCHAR(20) NOT NULL,
    classified_via VARCHAR(20) NOT NULL,
    classification_reason VARCHAR(1000) NOT NULL,
    classified_by BIGINT UNSIGNED NOT NULL,
    classified_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    classification_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    structure_revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    first_publish_receipt_id BIGINT UNSIGNED NULL DEFAULT NULL,
    latest_publish_receipt_id BIGINT UNSIGNED NULL DEFAULT NULL,
    adopted_at DATETIME NULL DEFAULT NULL,
    adopted_by BIGINT UNSIGNED NULL DEFAULT NULL,
    adoption_reason VARCHAR(1000) NULL DEFAULT NULL,
    adoption_evidence_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (subject_offering_id),
    UNIQUE KEY uq_governance_scope (subject_offering_id, school_id, academic_year_id),
    KEY ix_governance_epoch (school_id, cutover_epoch_key),
    KEY ix_governance_state (school_id, academic_year_id, origin, state, subject_offering_id),
    KEY ix_governance_first (first_publish_receipt_id, school_id, academic_year_id, subject_offering_id),
    KEY ix_governance_latest (latest_publish_receipt_id, school_id, academic_year_id, subject_offering_id),
    CONSTRAINT fk_governance_offering FOREIGN KEY (subject_offering_id, school_id, academic_year_id) REFERENCES subject_offerings (id, school_id, academic_year_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_governance_epoch FOREIGN KEY (school_id, cutover_epoch_key) REFERENCES gradebook_school_cutovers (school_id, epoch_key) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_governance_classified_by (classified_by),
    CONSTRAINT fk_governance_classified_by FOREIGN KEY (classified_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_governance_adopted_by (adopted_by),
    CONSTRAINT fk_governance_adopted_by FOREIGN KEY (adopted_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_governance_origin CHECK (origin IN ('PRE_ACTIVATION','POST_ACTIVATION')),
    CONSTRAINT ck_governance_state CHECK (state IN ('LEGACY','SETUP_REQUIRED','PUBLISHED')),
    CONSTRAINT ck_governance_source CHECK (classified_via IN ('INVENTORY','CREATE','IMPORT')),
    CONSTRAINT ck_governance_revisions CHECK (revision > 0 AND structure_revision > 0),
    CONSTRAINT ck_governance_origin_state CHECK ((origin = 'PRE_ACTIVATION' AND state IN ('LEGACY','PUBLISHED')) OR (origin = 'POST_ACTIVATION' AND state IN ('SETUP_REQUIRED','PUBLISHED'))),
    CONSTRAINT ck_governance_receipts CHECK ((state = 'PUBLISHED' AND first_publish_receipt_id IS NOT NULL AND latest_publish_receipt_id IS NOT NULL) OR (state <> 'PUBLISHED' AND first_publish_receipt_id IS NULL AND latest_publish_receipt_id IS NULL)),
    CONSTRAINT ck_governance_adoption CHECK ((origin = 'PRE_ACTIVATION' AND state = 'PUBLISHED' AND adopted_at IS NOT NULL AND adopted_by IS NOT NULL AND adoption_reason IS NOT NULL AND adoption_evidence_hash IS NOT NULL) OR ((origin <> 'PRE_ACTIVATION' OR state <> 'PUBLISHED') AND adopted_at IS NULL AND adopted_by IS NULL AND adoption_reason IS NULL AND adoption_evidence_hash IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
