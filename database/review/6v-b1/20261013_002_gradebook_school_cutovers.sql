CREATE TABLE gradebook_school_cutovers (
    school_id BIGINT UNSIGNED NOT NULL,
    epoch_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    phase VARCHAR(20) NOT NULL DEFAULT 'PREPARING',
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    inventory_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL,
    inventory_count BIGINT UNSIGNED NULL DEFAULT NULL,
    verified_release VARCHAR(64) NULL DEFAULT NULL,
    activation_reason VARCHAR(1000) NULL DEFAULT NULL,
    activated_at DATETIME NULL DEFAULT NULL,
    activated_by BIGINT UNSIGNED NULL DEFAULT NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (school_id),
    UNIQUE KEY uq_cutover_epoch (epoch_key),
    UNIQUE KEY uq_cutover_scope (school_id, epoch_key),
    KEY ix_cutover_phase (phase, school_id),
    CONSTRAINT fk_cutover_school FOREIGN KEY (school_id) REFERENCES schools (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_cutover_created_by (created_by),
    CONSTRAINT fk_cutover_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_cutover_updated_by (updated_by),
    CONSTRAINT fk_cutover_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_cutover_activated_by (activated_by),
    CONSTRAINT fk_cutover_activated_by FOREIGN KEY (activated_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_cutover_phase CHECK (phase IN ('PREPARING','ARMED','ACTIVE')),
    CONSTRAINT ck_cutover_revision CHECK (revision > 0),
    CONSTRAINT ck_cutover_inventory CHECK (phase = 'PREPARING' OR (inventory_hash IS NOT NULL AND inventory_count IS NOT NULL AND verified_release IS NOT NULL)),
    CONSTRAINT ck_cutover_activation CHECK ((phase = 'ACTIVE' AND activated_at IS NOT NULL AND activated_by IS NOT NULL AND activation_reason IS NOT NULL) OR (phase IN ('PREPARING','ARMED') AND activated_at IS NULL AND activated_by IS NULL AND activation_reason IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
