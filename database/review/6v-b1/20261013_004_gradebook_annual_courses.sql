CREATE TABLE gradebook_annual_courses (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    school_id BIGINT UNSIGNED NOT NULL,
    academic_year_id BIGINT UNSIGNED NOT NULL,
    classroom_id BIGINT UNSIGNED NOT NULL,
    course_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    name_th VARCHAR(190) NOT NULL,
    coursework_percent TINYINT UNSIGNED NULL DEFAULT NULL,
    final_percent TINYINT UNSIGNED NULL DEFAULT NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    ratio_frozen_at DATETIME NULL,
    ratio_frozen_by BIGINT UNSIGNED NULL DEFAULT NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_annual_key (course_key),
    UNIQUE KEY uq_annual_scope (id, school_id, academic_year_id, classroom_id),
    KEY ix_annual_classroom (classroom_id, school_id, academic_year_id),
    KEY ix_annual_status (school_id, academic_year_id, classroom_id, status, id),
    CONSTRAINT fk_annual_classroom FOREIGN KEY (classroom_id, school_id, academic_year_id) REFERENCES classrooms (id, school_id, academic_year_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_annual_created_by (created_by),
    CONSTRAINT fk_annual_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_annual_updated_by (updated_by),
    CONSTRAINT fk_annual_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_annual_ratio_frozen_by (ratio_frozen_by),
    CONSTRAINT fk_annual_ratio_frozen_by FOREIGN KEY (ratio_frozen_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_annual_ratio CHECK ((coursework_percent IS NULL AND final_percent IS NULL) OR (coursework_percent IS NOT NULL AND final_percent IS NOT NULL AND coursework_percent BETWEEN 1 AND 99 AND final_percent BETWEEN 1 AND 99 AND coursework_percent + final_percent = 100)),
    CONSTRAINT ck_annual_revision CHECK (revision > 0),
    CONSTRAINT ck_annual_status CHECK (status IN ('ACTIVE','ARCHIVED')),
    CONSTRAINT ck_annual_freeze CHECK ((ratio_frozen_at IS NULL AND ratio_frozen_by IS NULL) OR (ratio_frozen_at IS NOT NULL AND ratio_frozen_by IS NOT NULL AND coursework_percent IS NOT NULL AND final_percent IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
