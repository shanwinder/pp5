CREATE TABLE gradebook_annual_course_offerings (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    annual_course_id BIGINT UNSIGNED NOT NULL,
    school_id BIGINT UNSIGNED NOT NULL,
    academic_year_id BIGINT UNSIGNED NOT NULL,
    classroom_id BIGINT UNSIGNED NOT NULL,
    subject_id BIGINT UNSIGNED NOT NULL,
    term_no TINYINT UNSIGNED NOT NULL,
    subject_offering_id BIGINT UNSIGNED NOT NULL,
    published_annual_revision BIGINT UNSIGNED NULL DEFAULT NULL,
    published_at DATETIME NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_annual_term (annual_course_id, term_no),
    UNIQUE KEY uq_annual_offering (subject_offering_id),
    UNIQUE KEY uq_link_scope (subject_offering_id, school_id, academic_year_id),
    KEY ix_link_annual (annual_course_id, school_id, academic_year_id, classroom_id),
    KEY ix_link_offering (subject_offering_id, school_id, academic_year_id, classroom_id, subject_id, term_no),
    KEY ix_link_context (school_id, academic_year_id, classroom_id, subject_offering_id),
    CONSTRAINT fk_link_annual FOREIGN KEY (annual_course_id, school_id, academic_year_id, classroom_id) REFERENCES gradebook_annual_courses (id, school_id, academic_year_id, classroom_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_link_offering FOREIGN KEY (subject_offering_id, school_id, academic_year_id, classroom_id, subject_id, term_no) REFERENCES subject_offerings (id, school_id, academic_year_id, classroom_id, subject_id, term_no) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_link_governance FOREIGN KEY (subject_offering_id, school_id, academic_year_id) REFERENCES gradebook_offering_governance (subject_offering_id, school_id, academic_year_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_link_created_by (created_by),
    CONSTRAINT fk_link_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_link_updated_by (updated_by),
    CONSTRAINT fk_link_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_link_term CHECK (term_no IN (1,2)),
    CONSTRAINT ck_link_published CHECK ((published_annual_revision IS NULL AND published_at IS NULL) OR (published_annual_revision IS NOT NULL AND published_at IS NOT NULL AND published_annual_revision > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
