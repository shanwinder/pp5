CREATE TABLE gradebook_structure_drafts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    draft_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    school_id BIGINT UNSIGNED NOT NULL,
    academic_year_id BIGINT UNSIGNED NOT NULL,
    subject_offering_id BIGINT UNSIGNED NOT NULL,
    owner_user_id BIGINT UNSIGNED NOT NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    base_annual_revision BIGINT UNSIGNED NULL DEFAULT NULL,
    base_structure_revision BIGINT UNSIGNED NOT NULL,
    base_snapshot JSON NOT NULL,
    base_snapshot_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payload JSON NOT NULL,
    validation_errors JSON NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'EDITING',
    created_by BIGINT UNSIGNED NOT NULL,
    updated_by BIGINT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_draft_key (draft_key),
    UNIQUE KEY uq_draft_owner (school_id, subject_offering_id, owner_user_id),
    UNIQUE KEY uq_draft_scope (id, school_id, academic_year_id, subject_offering_id),
    KEY ix_draft_offering (subject_offering_id, school_id, academic_year_id),
    KEY ix_draft_status (school_id, subject_offering_id, status, updated_at),
    CONSTRAINT fk_draft_governance FOREIGN KEY (subject_offering_id, school_id, academic_year_id) REFERENCES gradebook_offering_governance (subject_offering_id, school_id, academic_year_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_draft_created_by (created_by),
    CONSTRAINT fk_draft_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_draft_updated_by (updated_by),
    CONSTRAINT fk_draft_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    KEY ix_draft_owner_user_id (owner_user_id),
    CONSTRAINT fk_draft_owner_user_id FOREIGN KEY (owner_user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_draft_revisions CHECK (revision > 0 AND base_structure_revision > 0 AND (base_annual_revision IS NULL OR base_annual_revision > 0)),
    CONSTRAINT ck_draft_status CHECK (status IN ('EDITING','PUBLISHED','ARCHIVED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
